#!/usr/bin/env python3
"""Build docs/gym-audit.md + docs/gym-audit.html from gym-matrix.json and gym_verdicts.py.

Usage (repo root): python3 scripts/vision-audit/build_gym_report.py [/tmp/gt-audit-work/gym-matrix.json]
The HTML embeds start + mid-rep thumbnails (base64) so it works as a single file on a phone.
"""
import base64, html, io, json, os, re, sys
from collections import OrderedDict
from PIL import Image

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(os.path.dirname(HERE))
MEDIA = os.path.join(ROOT, "apps/web/public/exercise-media")
sys.path.insert(0, HERE)
from gym_verdicts import V, NOTES  # noqa: E402

matrix = sys.argv[1] if len(sys.argv) > 1 else "/tmp/gt-audit-work/gym-matrix.json"
rows = json.load(open(matrix))["rows"]
edb = {x["id"]: x["name"] for x in json.load(open(os.path.join(ROOT, "apps/web/public/edb/exercises.json")))}
KIND = {"bar": "Barbell", "cable": "Cable", "machine": "Machine", "db": "Dumbbell", "bw": "Bodyweight"}
ID_RE = re.compile(r"^([A-Za-z0-9]{7})\b")

for r in rows:
    v = V.get(r["n"])
    r["verdict"], r["checks"], r["problem"], r["cand"] = v if v else ("MATCH", "", NOTES.get(r["n"], ""), "")
    r["where"] = "gym" if r["inGymTabs"] else " + ".join(sorted({o.split(":")[0].replace("cal", "calisthenics") for o in r["owners"]})) or "none"
    shown = r["chip"] or r["catalogLabel"] or next((o.split(":", 1)[1] for o in r["owners"]), None) or r["name"]
    r["shown"] = shown
    r["role"] = "default" if r["isDefault"] else ("chip" if r["chip"] else "unreachable")

def count(sel):
    c = {"MATCH": 0, "MISMATCH": 0, "UNCLEAR": 0}
    for r in sel:
        c[r["verdict"]] += 1
    return c

gym = [r for r in rows if r["inGymTabs"]]
other = [r for r in rows if not r["inGymTabs"]]
cg, co, ca = count(gym), count(other), count(rows)
ids_gym = len({r["id"] for r in gym})
ids_all = len({r["id"] for r in rows})
known = [r for r in rows if r["checks"] and "3" in r["checks"] and "known" in r["problem"]]

def ex_cell(r):
    return f"`{r['id']}` {r['shown']}" + (f" (EDB: {edb.get(r['id'], '?')})" if edb.get(r["id"], "").lower() != r["shown"].lower() else "")

# ---------------- Markdown ----------------
L = [
    "# Gym exercise visual audit",
    "",
    "Audit only — nothing in the app was changed. Generated by `scripts/vision-audit/build_gym_report.py` "
    "from the real resolver (`resolveExercise` + style-variant chips) on `origin/main` @ the commit this file lands on.",
    "",
    "**How each row was checked:** the animated webp was viewed at 4 frames (start, ¼, ½, ¾) and compared against "
    "(1) the exercise named on the card/sheet, (2) the highlighted muscle vs. the declared target/secondary, "
    "(3) the exercise's equipment vs. the tab it sits under, (4) the steps + card cue text. Every suggested replacement id "
    "was viewed the same way. Vision was done in-session (no paid API).",
    "",
    "## Counts",
    "",
    "| Scope | Rows | Unique exercises | MATCH | MISMATCH | UNCLEAR |",
    "|---|---|---|---|---|---|",
    f"| Gym tabs (what the gym Train card + sheet can show) | {len(gym)} | {ids_gym} | {cg['MATCH']} | {cg['MISMATCH']} | {cg['UNCLEAR']} |",
    f"| Other tabs on the same shared slots (calisthenics / travel) | {len(other)} | — | {co['MATCH']} | {co['MISMATCH']} | {co['UNCLEAR']} |",
    f"| **Total** | **{len(rows)}** | **{ids_all}** | **{ca['MATCH']}** | **{ca['MISMATCH']}** | **{ca['UNCLEAR']}** |",
    "",
    "A *row* is one (slot, tab, exercise): the tab's default plus every style-variant chip, plus any id filed under the tab "
    "that the UI can't reach. Slots are shared across plans, so a fix to a gym slot also changes the calisthenics/travel "
    "tabs listed in the second row — they're audited here too.",
    "",
    "Candidate rules applied: EDB 3D animation first; free-exercise-db photo only as a flagged last resort (⚠); no "
    "bars/benches/bands on travel or floor slots; no exercise reused by another slot; where EDB has nothing right for a "
    "tab, **REMOVE the tab** rather than keep a wrong one.",
    "",
    "## The 13 known equipment mismatches (exercises.test.ts `KNOWN_MISMATCHES`)",
    "",
    "| Slot | Tab | Exercise | Verdict | Recommendation |",
    "|---|---|---|---|---|",
]
for r in sorted(known, key=lambda r: (r["slot"], r["kind"])):
    L.append(f"| {r['slot']} | {KIND[r['kind']]} | {ex_cell(r)} | {r['verdict']} | {r['cand']} |")
L += ["", "## All mismatches", ""]
for r in rows:
    if r["verdict"] == "MISMATCH":
        L.append(f"- **{r['slot']} › {KIND[r['kind']]}** ({r['where']}) — {ex_cell(r)}: {r['problem']} → _{r['cand']}_")
L += ["", "## Per slot", "",
      "Checks column: which of the 4 checks failed (1 animation · 2 muscle · 3 equipment · 4 text).", ""]
by_slot = OrderedDict()
for r in rows:
    by_slot.setdefault(r["slot"], []).append(r)
for slot, rs in by_slot.items():
    L += [f"### {slot}", "", "| Tab | Shown in | Current exercise | Role | Verdict | Checks | Problem | Best replacement |",
          "|---|---|---|---|---|---|---|---|"]
    for r in rs:
        L.append(f"| {KIND[r['kind']]} | {r['where']} | {ex_cell(r)} | {r['role']} | **{r['verdict']}** | {r['checks']} | "
                 f"{r['problem'].replace('|', '/')} | {r['cand'].replace('|', '/')} |")
    L.append("")
L += ["## Method notes", "",
      "- EDB highlights quads on squats/lunges even when the declared target is glutes; that alone was not marked a mismatch.",
      "- The card title is the catalog variation name (or the chip name), the cue comes from `catalog.plans.<plan>.cues`, "
      "the muscle tags + steps come from the exercise; all were compared to the animation.",
      "- Slot names that hide a reused id (e.g. Leg Press under both Squat and Lunge) are flagged as duplicates.",
      "- Re-run: `scripts/vision-audit/dump_gym_matrix.ts` → `gym_frame_strips.py` (view the strips) → edit "
      "`gym_verdicts.py` → `build_gym_report.py`."]
os.makedirs(os.path.join(ROOT, "docs"), exist_ok=True)
open(os.path.join(ROOT, "docs/gym-audit.md"), "w").write("\n".join(L) + "\n")

# ---------------- HTML ----------------
thumb_cache = {}
def thumbs(i):
    if i in thumb_cache:
        return thumb_cache[i]
    out = []
    p = os.path.join(MEDIA, f"{i}.webp")
    if os.path.exists(p):
        im = Image.open(p)
        n = getattr(im, "n_frames", 1)
        for fr in (0, n // 2):
            im.seek(fr)
            b = io.BytesIO()
            im.convert("RGB").resize((120, 120), Image.LANCZOS).save(b, "JPEG", quality=70)
            out.append("data:image/jpeg;base64," + base64.b64encode(b.getvalue()).decode())
    thumb_cache[i] = out
    return out

def imgs(i, alt):
    return "".join(f'<img src="{s}" alt="{html.escape(alt)} frame {k + 1}" width="60" height="60" loading="lazy">' for k, s in enumerate(thumbs(i)))

esc = html.escape
cards = []
for slot, rs in by_slot.items():
    items = []
    for r in rs:
        m = ID_RE.match(r["cand"])
        cand_img = imgs(m.group(1), r["cand"]) if m and m.group(1) in edb else ""
        items.append(f"""
<li class="row v-{r['verdict'].lower()}{' other' if not r['inGymTabs'] else ''}" data-v="{r['verdict']}" data-scope="{'gym' if r['inGymTabs'] else 'other'}">
  <div class="top"><span class="tab">{KIND[r['kind']]}</span><span class="where">{esc(r['where'])} · {r['role']}</span><span class="badge">{r['verdict']}</span></div>
  <div class="ex"><div class="th">{imgs(r['id'], r['shown'])}</div>
    <div><b>{esc(r['shown'])}</b><div class="mono">{r['id']} · {esc(edb.get(r['id'], ''))} · {esc(r['equipment'])} · {esc(r['target'])}</div></div></div>
  {f'<p class="prob">{"<span class=chk>checks " + esc(r["checks"]) + "</span> " if r["checks"] else ""}{esc(r["problem"])}</p>' if r['problem'] else ''}
  {f'<div class="cand"><div class="th">{cand_img}</div><div><span class="lbl">Replace with</span> {esc(r["cand"])}</div></div>' if r['cand'] else ''}
</li>""")
    bad = sum(1 for r in rs if r["verdict"] != "MATCH")
    cards.append(f'<section class="slot"><h2>{esc(slot)} <small>{len(rs)} rows{f" · {bad} to review" if bad else ""}</small></h2><ul>{"".join(items)}</ul></section>')

